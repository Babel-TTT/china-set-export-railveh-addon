#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Check that every gorender manifest and palette is the canonical one.

``make sprites`` reads a ``manifest.json`` and a ``ttd_palette.json`` from the
folder each ``.vox`` lives in, and ``src/template.pnml`` crops the sheets with
exactly the rectangles the manifest describes, so a single stray copy silently
changes how a model is rendered -- or how it is cut out.

Both files come from China-Set-Trains.  The manifest is generated by
``genpnml.py`` (``write_manifest``) and the palette is copied from
``<gfx>/ttd_palette.json``; this check compares what is on disk against those
sources and against each other.

Line endings are ignored when comparing *content*, because this project is LF
(see .gitattributes) while China-Set-Trains is CRLF.  Digests are always taken
over the raw bytes, so what is printed can be reproduced with md5sum.

Usage:
    python3 tools/check_gfx_config.py
    python3 tools/check_gfx_config.py --reference /path/to/China-Set-Trains
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_REFERENCE = Path(r"D:\CNS\CNST\local\China-Set-Trains")


def read_text(path: Path) -> str:
    """The file's text with the line endings normalised to LF."""
    return path.read_bytes().decode("utf-8-sig").replace("\r\n", "\n")


def raw_digest(path: Path) -> str:
    """MD5 of the file as stored, so it can be checked against md5sum."""
    return hashlib.md5(path.read_bytes()).hexdigest()


def content_digest(path: Path) -> str:
    """MD5 of the line ending normalised text."""
    return hashlib.md5(read_text(path).encode("utf-8")).hexdigest()


def manifests() -> list:
    return sorted(path for path in (ROOT / "gfx").rglob("manifest.json"))


def palettes() -> list:
    found = sorted(path for path in (ROOT / "gfx").rglob("ttd_palette.json"))
    top = ROOT / "ttd_palette.json"
    if top.is_file():
        found.insert(0, top)
    return found


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--reference", default=str(DEFAULT_REFERENCE),
                        help="a China-Set-Trains checkout to compare against")
    args = parser.parse_args(argv)

    reference = Path(args.reference)
    failures = []

    # ---- the manifest: one shape, and the generator must reproduce it
    sys.path.insert(0, str(ROOT))
    try:
        import genpnml
    except ImportError as error:
        print("cannot import genpnml: %s" % error)
        return 1

    probe = ROOT / ".genpnml-manifest-probe.json"
    genpnml.write_manifest(str(probe))
    expected = json.loads(read_text(probe))
    probe.unlink()
    expected_key = json.dumps(expected, sort_keys=True)

    files = manifests()
    print("manifests on disk: %d" % len(files))
    for path in files:
        try:
            shape = json.loads(read_text(path))
        except json.JSONDecodeError as error:
            failures.append("%s is not valid JSON: %s" % (path, error))
            continue
        ok = json.dumps(shape, sort_keys=True) == expected_key
        print("  %-40s content=%s  %s" % (path.relative_to(ROOT),
                                          content_digest(path)[:8],
                                          "matches the generator" if ok else "DIFFERENT"))
        if not ok:
            failures.append("%s does not match what genpnml.write_manifest() "
                            "produces, so renderobject and src/template.pnml "
                            "would disagree about the layout" % path.relative_to(ROOT))

    views = expected.get("sprites") or []
    print("  canonical: %d views %s" % (len(views), ", ".join(
        "%dx%d" % (row.get("width"), row.get("height")) for row in views)))

    # ---- the palette: every copy has to be the same file
    palette_files = palettes()
    print("palettes on disk: %d" % len(palette_files))
    by_content = {}
    for path in palette_files:
        by_content.setdefault(content_digest(path), []).append(path)
        print("  %-40s bytes=%-6d raw=%s content=%s"
              % (path.relative_to(ROOT), path.stat().st_size, raw_digest(path)[:8],
                 content_digest(path)[:8]))
    if len(by_content) > 1:
        failures.append("the gfx palettes are not all the same file: %d different "
                        "contents among %d copies" % (len(by_content), len(palette_files)))
    else:
        print("  all %d copies hold the same content (line endings aside)" % len(palette_files))
        print("  note: the raw digest differs between CRLF and LF checkouts, so the "
              "content digest is the one that matters")

    # ---- and the same file as the reference checkout, if there is one
    if reference.is_dir():
        candidates = [path for path in reference.rglob("ttd_palette.json")
                      if ".git" not in path.parts]
        if candidates:
            counts = {}
            for path in candidates:
                counts.setdefault(content_digest(path), []).append(path)
            commonest = max(counts.values(), key=len)
            reference_digest = content_digest(commonest[0])
            ours = content_digest(palette_files[0]) if palette_files else ""
            print("reference: %d palette copies, %d distinct contents; the "
                  "commonest is in %d of them"
                  % (len(candidates), len(counts), len(commonest)))
            if reference_digest != ours:
                failures.append("the palette differs from the commonest one in %s"
                                % reference)
            else:
                print("  the palette matches the reference")

        ref_manifests = [path for path in reference.rglob("manifest.json")
                         if ".git" not in path.parts]
        if ref_manifests:
            keys = {json.dumps(json.loads(read_text(path)), sort_keys=True)
                    for path in ref_manifests}
            print("reference: %d manifests, %d distinct contents"
                  % (len(ref_manifests), len(keys)))
            if keys == {expected_key}:
                print("  the manifest matches the reference")
            elif expected_key not in keys:
                failures.append("the manifest content differs from every manifest "
                                "in %s" % reference)
            else:
                print("  the manifest matches one of the reference's contents")
    else:
        print("reference %s not found, skipping the comparison" % reference)

    print()
    if failures:
        for failure in failures:
            print("FAIL %s" % failure)
        print("FAILURES: %d" % len(failures))
        return 1
    print("FAILURES: none")
    return 0


if __name__ == "__main__":
    sys.exit(main())
